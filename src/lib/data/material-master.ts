export const SUBSTRATES = MATERIAL_MASTER.filter((m) => m.category === "substrate");
export const FINISHES = MATERIAL_MASTER.filter((m) => m.category === "laminate");
export const ADHESIVES = MATERIAL_MASTER.filter((m) => m.category === "adhesive");

export function findMaterial(
  query: string | undefined,
  materials: Material[] = MATERIAL_MASTER
): Material | undefined {
  if (!query?.trim()) return undefined;
  const q = query.trim().toLowerCase();
  return (
    materials.find((m) => m.id === q || m.sku.toLowerCase() === q) ??
    materials.find((m) => m.name.toLowerCase() === q) ??
    materials.find((m) => m.aliases.some((a) => a === q)) ??
    materials.find(
      (m) =>
        m.active &&
        (m.name.toLowerCase().includes(q) ||
          q.includes(m.name.toLowerCase()) ||
          m.aliases.some((a) => q.includes(a) || a.includes(q)))
    )
  );
}
